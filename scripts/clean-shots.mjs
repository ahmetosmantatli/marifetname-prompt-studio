import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ headless: 'new', executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--no-sandbox','--disable-gpu'], userDataDir: '/tmp/mps-puppeteer-clean' });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 1100, deviceScaleFactor: 1 });
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle0' });
await new Promise(r=>setTimeout(r,900));
await page.click('.generate-btn');
await page.waitForSelector('.result-head', { timeout: 20000 });
await new Promise(r=>setTimeout(r,3200));
await page.evaluate(()=>window.scrollTo(0,0));
const panel = await page.$('.result-panel');
if (panel) await panel.screenshot({ path: 'docs/screenshot-result.png' });
await page.screenshot({ path: 'docs/screenshot-home.png' });
const mobile = await browser.newPage();
await mobile.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await mobile.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle0' });
await new Promise(r=>setTimeout(r,900));
await mobile.screenshot({ path: 'docs/screenshot-mobile.png' });
await browser.close();
